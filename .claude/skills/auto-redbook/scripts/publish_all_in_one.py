def extract_generated_images(combined_output: str, skill_dir: Path, task_id: str) -> list[str]:
    """
    Extract only current task images from generator output.
    Prevent stale images from previous runs being mixed into publish payload.
    """
    cover_path = None
    image_map: dict[int, Path] = {}
    pattern = re.compile(rf"{re.escape(task_id)}_(cover|image_(\d+))\.(?:jpg|png)")

    for raw_line in combined_output.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        m = pattern.search(line)
        if not m:
            continue
        rel_name = m.group(0)
        p = skill_dir / rel_name
        if not p.exists():
            continue
        if m.group(1) == "cover":
            cover_path = p
        else:
            idx = int(m.group(2))
            image_map[idx] = p

    ordered = []
    if cover_path:
        ordered.append(str(cover_path))
    ordered.extend(str(image_map[i]) for i in sorted(image_map))

    if ordered:
        return ordered

    # Fallback only within current task_id (never scan all historical files).
    cover = skill_dir / f"{task_id}_cover.jpg"
    if not cover.exists():
        cover = skill_dir / f"{task_id}_cover.png"
    if cover.exists():
        ordered.append(str(cover))

    for p in sorted(skill_dir.glob(f"{task_id}_image_*.jpg")):
        ordered.append(str(p))
    if not ordered:
        for p in sorted(skill_dir.glob(f"{task_id}_image_*.png")):
            ordered.append(str(p))
    return ordered


