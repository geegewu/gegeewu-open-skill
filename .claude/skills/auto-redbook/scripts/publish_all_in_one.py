def get_env_int(name: str, default: int, min_value: int = 0, max_value = None) -> int:
    """Read integer env with clamp and safe fallback."""
    raw = os.environ.get(name, "").strip()
    if not raw:
        return default
    try:
        value = int(raw)
    except ValueError:
        print(f"  ⚠️ 环境变量 {name} 非整数({raw})，使用默认值 {default}")
        return default

    if value < min_value:
        print(f"  ⚠️ 环境变量 {name}={value} 低于最小值 {min_value}，使用 {min_value}")
        value = min_value
    if max_value is not None and value > max_value:
        print(f"  ⚠️ 环境变量 {name}={value} 高于最大值 {max_value}，使用 {max_value}")
        value = max_value
    return value


def get_env_bool(name: str, default: bool = False) -> bool:
    raw = os.environ.get(name, "").strip().lower()
    if not raw:
        return default
    return raw in {"1", "true", "yes", "on"}


