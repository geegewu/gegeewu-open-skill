def acquire_mcp_lock(
    task_name: str,
    max_wait: int = MCP_LOCK_MAX_WAIT,
    poll_interval: int = MCP_LOCK_POLL_INTERVAL,
    stale_lock_minutes: int = MCP_STALE_LOCK_MINUTES,
) -> bool:
    waited = 0
    while waited < max_wait:
        if MCP_LOCK_FILE.exists():
            try:
                pid, name, ts = MCP_LOCK_FILE.read_text().strip().split("|")
                if datetime.now() - datetime.fromisoformat(ts) > timedelta(minutes=stale_lock_minutes):
                    print(f"  ⚠️ 僵死锁({name})，强制清除")
                    MCP_LOCK_FILE.unlink(missing_ok=True)
                else:
                    sleep_for = min(poll_interval, max_wait - waited)
                    print(f"  ⏳ MCP被{name}占用，{sleep_for}s后重试... (已等{waited}s)")
                    time.sleep(sleep_for)
                    waited += sleep_for
                    continue
            except Exception:
                MCP_LOCK_FILE.unlink(missing_ok=True)
        MCP_LOCK_FILE.write_text(f"{os.getpid()}|{task_name}|{datetime.now().isoformat()}")
        atexit.register(release_mcp_lock)
        print(f"  🔒 MCP锁已获取: {task_name}")
        return True
    if max_wait == 0 and not MCP_LOCK_FILE.exists():
        MCP_LOCK_FILE.write_text(f"{os.getpid()}|{task_name}|{datetime.now().isoformat()}")
        atexit.register(release_mcp_lock)
        print(f"  🔒 MCP锁已获取: {task_name}")
        return True
    print(f"  ❌ 等待MCP锁超时({max_wait}s)")
    return False

def release_mcp_lock():
    if MCP_LOCK_FILE.exists():
        try:
            if MCP_LOCK_FILE.read_text().strip().startswith(str(os.getpid())):
                MCP_LOCK_FILE.unlink(missing_ok=True)
                print("  🔓 MCP锁已释放")
        except Exception:
            pass

