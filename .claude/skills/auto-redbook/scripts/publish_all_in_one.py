def check_cookie_expiry() -> tuple:
    """本地检查cookie过期，避免触发go-rod"""
    cookies_file = SKILL_DIR / "tools" / "cookies.json"
    if not cookies_file.exists():
        return False, "cookies.json不存在"
    try:
        import json
        cookies = json.loads(cookies_file.read_text())
        now = datetime.now().timestamp()
        for c in cookies:
            if c.get("expires", 0) > now + 3600:
                return True, f"cookie有效(至少剩余{((c['expires']-now)/3600):.1f}h)"
        return False, "所有cookie已过期或即将过期"
    except Exception as e:
        return True, f"cookie检查异常({e})，跳过"
